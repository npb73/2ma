#!/usr/bin/env node
/**
 * Scans shared/src/maps/*.json and writes catalog.gen.ts.
 * Drop a map editor export into that folder — no manual registry edits.
 *
 * Usage:
 *   node shared/scripts/gen-map-catalog.mjs
 *   node shared/scripts/gen-map-catalog.mjs --watch
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MAPS_DIR = path.resolve(__dirname, "../src/maps");
const OUT_FILE = path.join(MAPS_DIR, "catalog.gen.ts");

function listJsonFiles() {
  return fs
    .readdirSync(MAPS_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort();
}

function importIdent(fileName) {
  const base = fileName.replace(/\.json$/i, "");
  const ident = `map_${base.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^_+|_+$/g, "")}`;
  if (!/^[a-zA-Z_]/.test(ident)) return `_${ident}`;
  return ident;
}

function readMapMeta(fileName) {
  const raw = JSON.parse(fs.readFileSync(path.join(MAPS_DIR, fileName), "utf8"));
  if (!raw || typeof raw !== "object") {
    throw new Error(`${fileName}: root must be an object`);
  }
  if (raw.version !== 1) {
    throw new Error(`${fileName}: unsupported version`);
  }
  if (typeof raw.id !== "string" || !raw.id) {
    throw new Error(`${fileName}: missing id`);
  }
  if (raw.players !== 1 && raw.players !== 2) {
    throw new Error(`${fileName}: players must be 1 or 2`);
  }
  if (typeof raw.name !== "string") {
    throw new Error(`${fileName}: missing name`);
  }
  return { id: raw.id, name: raw.name, players: raw.players };
}

export function generateMapCatalog() {
  const files = listJsonFiles();
  if (files.length === 0) {
    throw new Error(`No map JSON files in ${MAPS_DIR}`);
  }

  const metas = files.map((f) => ({ file: f, ...readMapMeta(f) }));
  const seen = new Set();
  for (const m of metas) {
    if (seen.has(m.id)) {
      throw new Error(`Duplicate map id "${m.id}" (file ${m.file})`);
    }
    seen.add(m.id);
  }

  const imports = files
    .map((f) => {
      const id = importIdent(f);
      return `import ${id} from "./${f}" with { type: "json" };`;
    })
    .join("\n");

  const parses = files
    .map((f) => `  parseGameMap(${importIdent(f)}),`)
    .join("\n");

  const summary = metas
    .map((m) => ` * - ${m.id} (${m.players}p) ← ${m.file}`)
    .join("\n");

  const body = `/* eslint-disable */
/**
 * AUTO-GENERATED by shared/scripts/gen-map-catalog.mjs — do not edit.
 * Source folder: shared/src/maps/*.json
 *
${summary}
 */
import { parseGameMap, type GameMap } from "../map.js";
${imports}

const MAPS: GameMap[] = [
${parses}
];

export const MAP_CATALOG: Readonly<Record<string, GameMap>> = Object.freeze(
  Object.fromEntries(MAPS.map((m) => [m.id, m])),
);
`;

  const prev = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : null;
  if (prev === body) return { changed: false, files };
  fs.writeFileSync(OUT_FILE, body);
  return { changed: true, files };
}

function main() {
  const watch = process.argv.includes("--watch");
  const run = () => {
    try {
      const { changed, files } = generateMapCatalog();
      const msg = changed ? "updated" : "up-to-date";
      console.log(`[maps] catalog.gen.ts ${msg} (${files.length} maps)`);
    } catch (e) {
      console.error("[maps]", e instanceof Error ? e.message : e);
      if (!watch) process.exitCode = 1;
    }
  };

  run();
  if (!watch) return;

  console.log(`[maps] watching ${MAPS_DIR}`);
  let timer = null;
  const kick = () => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(run, 80);
  };
  fs.watch(MAPS_DIR, { persistent: true }, (_event, fileName) => {
    if (!fileName || !fileName.endsWith(".json")) return;
    kick();
  });
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) main();
